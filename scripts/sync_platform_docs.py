"""Generate Wiki/legacy manual views from the same tutorials consumed by the UI and MCP.

Run after editing docs/manual/{en,zh}/*.md or catalog.json; --check verifies parity.
"""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]
LEGACY = {
    'AgentManual': ('agent', 'CN'), 'ReportManual': ('researcher', 'CN'),
    'WorkspaceManual': ('library', 'CN'), 'TrainingManual': ('training', 'ZH'),
    'PredictionManual': ('prediction', 'ZH'), 'EvaluationManual': ('evaluation', 'ZH'),
    'QuickTools': ('models', 'CN'), 'AdvancedToolsManual': ('models', 'CN'),
    'DownloadManual': ('data', 'ZH'), 'QAManual': ('faq', 'ZH'),
}


def generated_files(root=ROOT):
    manual = root / 'docs/manual'
    catalog = json.loads((manual / 'catalog.json').read_text(encoding='utf-8'))
    sections = {s['key']: s for s in catalog['sections']}
    aliases = {alias: s['key'] for s in sections.values() for alias in s['aliases']}
    outputs = {}
    def target(key, lang, wiki):
        key = aliases.get(key, key)
        item = sections[key]
        return './' + item['wiki'] + ('_CN' if lang == 'zh' else '') + '.md' if wiki else './' + item['files'][lang]
    def rewrite(text, lang, wiki):
        return re.sub(r'\(manual:([a-z-]+)\)', lambda m: '('+target(m[1],lang,wiki)+')', text)
    for lang in ['en', 'zh']:
        bodies = {}
        for key, item in sections.items():
            text = (manual / item['files'][lang]).read_text(encoding='utf-8')
            bodies[key] = text
            name = item['wiki'] + ('_CN' if lang == 'zh' else '') + '.md'
            outputs['docs/wiki/'+name] = '<!-- Generated by scripts/sync_platform_docs.py; edit docs/manual/'+item['files'][lang]+' -->\n\n' + rewrite(text,lang,True)
        for stem,(key,zh_suffix) in LEGACY.items():
            name = stem + ('_'+zh_suffix if lang == 'zh' else '_EN') + '.md'
            outputs['docs/manual/'+name] = '<!-- Compatibility view; edit '+sections[key]['files'][lang]+' -->\n\n'+rewrite(bodies[key],lang,False)
        # Existing Wiki links keep working without maintaining competing instructions.
        for old,key in [('Overview','start'),('WebUI','start'),('Usage','agent'),('Datasets','data'),('Checkpoints','models')]:
            suffix = '_CN' if lang == 'zh' else ''
            outputs['docs/wiki/'+old+suffix+'.md'] = '<!-- Generated compatibility view; edit docs/manual/'+sections[key]['files'][lang]+' -->\n\n'+rewrite(bodies[key],lang,True)
    intro = '# VenusFactory2 documentation\n\nManual, Wiki and the Agent documentation tool share `docs/manual/catalog.json` and `docs/manual/en/` / `zh/` tutorials.\n\n'
    table = '| English | 中文 |\n| --- | --- |\n'
    for item in sections.values():
        table += f"| [{item['title']['en']}](./{item['wiki']}.md) | [{item['title']['zh']}](./{item['wiki']}_CN.md) |\n"
    outputs['docs/wiki/Home.md'] = intro+table+'\nInstallation: [English](./Installation.md) · [中文](./Installation_CN.md)\n'
    outputs['docs/manual/README.md'] = '# Platform tutorials\n\nRead tutorials in the in-app Manual or [Wiki](../wiki/Home.md). Agent reads the same source through `query_platform_manual`.\n\nEdit `catalog.json` and the `en/` / `zh/` pages here. Run `python scripts/sync_platform_docs.py` from the repository root to regenerate Wiki and legacy filenames; `--check` verifies consistency. Do not edit generated views separately.\n'
    outputs['docs/README.md'] = '# Documentation\n\n- [User tutorials and Wiki](./wiki/Home.md): Chat modes, Model Plaza, workflows, training, prediction, evaluation, files and settings.\n- [Installation](./wiki/Installation.md) · [安装](./wiki/Installation_CN.md).\n- [Architecture](./architecture/): implementation and operational notes.\n- [Repository layout](./architecture/repository-layout.md): source ownership, runtime data and skills.\n- [Model integration](./architecture/model-integration.md): pretrained, factory-trained and RSI model contracts.\n\nThe in-app Manual and Agent use the canonical tutorials in `docs/manual/en/` and `docs/manual/zh/`, indexed by `docs/manual/catalog.json`. Wiki pages and historical manual filenames are generated by `python scripts/sync_platform_docs.py`; verify with `--check`. Update tutorials when behavior changes, and review both languages. Agent retrieves relevant sections instead of loading all documentation into each prompt.\n'
    return outputs


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    stale = []
    for name, text in generated_files().items():
        path = ROOT / name
        if path.exists() and path.read_text(encoding='utf-8') == text:
            continue
        stale.append(name)
        if not args.check:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(text,encoding='utf-8',newline='\n')
    if args.check and stale:
        raise SystemExit('Documentation views are stale; run python scripts/sync_platform_docs.py:\n'+'\n'.join(stale))
    print('Documentation views are consistent' if args.check else f'Updated {len(stale)} documentation views')


if __name__ == '__main__':
    main()
